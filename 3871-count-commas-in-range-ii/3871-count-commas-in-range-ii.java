class Solution {
    public long countCommas(long n) {

        if (n < 1000) {
            return 0;
        }

        if (n < 1_000_000) {
            return n - 999;
        }

        if (n < 1_000_000_000) {
            return (n - 999_999) + (n - 999);
        }

        if (n < 1_000_000_000_000L) {
            return (n - 999_999_999)
                 + (n - 999_999)
                 + (n - 999);
        }

        if (n < 1_000_000_000_000_000L) {
            return (n - 999_999_999_999L)
                 + (n - 999_999_999)
                 + (n - 999_999)
                 + (n - 999);
        }

        return (n - 999_999_999_999_999L)
             + (n - 999_999_999_999L)
             + (n - 999_999_999)
             + (n - 999_999)
             + (n - 999);
    }
}